public class code12 {
     public static void main(String[] args) {
        int N = 10; // change N to any number you want
        int sum = 0;

        for (int i = 1; i <= N; i++) {
            sum += i;
        }

        System.out.println("Sum of first " + N + " numbers is: " + sum);
    }
}
    

